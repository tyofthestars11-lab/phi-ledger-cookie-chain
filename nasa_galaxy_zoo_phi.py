#!/usr/bin/env python3
"""NASA Galaxy Zoo lane — run the phi-lens over the real Hart16 catalog.

Source: gz2_hart16.csv.gz (Hart et al. 2016, Galaxy Zoo 2 Table 1,
Galaxy Zoo / Zooniverse, a NASA grantee platform). Catalog resolves to
this script's folder first, then ~/workspace/gz2-phi/.

Every galaxy read is all math, all phi:
  rung(x)  = ln(x) / ln(phi)
  drift(x) = rung(x) - round(rung(x))

Output: NASA_GALAXY_ZOO_PHI_REPORT.md beside this script.
Needs: numpy, pandas (requirements.txt), catalog on the local rail.
"""
import json
import math
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
FALLBACK = os.path.expanduser("~/workspace/gz2-phi")
PHI = (1 + math.sqrt(5)) / 2
LN_PHI = math.log(PHI)
FIB = {1, 2, 3, 5}

SPIRAL_FLAG = "t04_spiral_a08_spiral_flag"
ARM_DEB = [
    "t11_arms_number_a31_1_debiased",
    "t11_arms_number_a32_2_debiased",
    "t11_arms_number_a33_3_debiased",
    "t11_arms_number_a34_4_debiased",
    "t11_arms_number_a36_more_than_4_debiased",
]
ARM_LABEL = ["1", "2", "3", "4", "5+"]
WIND = {
    "tight": "t10_arms_winding_a28_tight_debiased",
    "medium": "t10_arms_winding_a29_medium_debiased",
    "loose": "t10_arms_winding_a30_loose_debiased",
}


def rung(x):
    return math.log(x) / LN_PHI


def catalog_path():
    p = os.path.join(HERE, "gz2_hart16.csv.gz")
    return p if os.path.exists(p) else os.path.join(FALLBACK, "gz2_hart16.csv.gz")


def argmax_reads(df, cols):
    v = df[cols].to_numpy(dtype=float)
    valid = (~np.isnan(v)).any(axis=1) & (np.nan_to_num(v, nan=0).max(axis=1) > 0)
    am = np.nanargmax(np.nan_to_num(v, nan=-1), axis=1)
    counts = [int(((am == i) & valid).sum()) for i in range(len(cols))]
    return counts, int(valid.sum())


def main():
    src = catalog_path()
    if not os.path.exists(src):
        raise SystemExit(f"missing catalog: {src} — get gz2_hart16.csv.gz from data.galaxyzoo.org")
    df = pd.read_csv(src, usecols=["dr7objid"] + [SPIRAL_FLAG] + ARM_DEB + list(WIND.values()))
    spir = df[df[SPIRAL_FLAG] == 1]
    arm_counts, arm_valid = argmax_reads(spir, ARM_DEB)
    wind_counts, wind_valid = argmax_reads(spir, list(WIND.values()))
    fib_subjects = sum(c for i, c in enumerate(arm_counts) if (i + 1) in FIB or i == 4)
    # i == 4 is the "5+" bin, read as the Fibonacci 5 arm family
    spiral_fraction = len(spir) / len(df) * 100

    lines = []
    lines.append("# NASA GALAXY ZOO — PHI-LENS REPORT")
    lines.append("")
    lines.append("Lane: Galaxy Zoo (Zooniverse, a NASA grantee platform) — spiral arm count read through the phi-lens.")
    lines.append("Source catalog: gz2_hart16.csv.gz — Hart et al. 2016, Galaxy Zoo 2 Table 1 (data.galaxyzoo.org).")
    lines.append("Steward: Tyree Jones (tyofthestarz). All math, all phi: rung(x) = ln(x)/ln(phi), phi^2 = phi + 1.")
    lines.append("")
    lines.append("## The catalog, read whole")
    lines.append("")
    lines.append(f"- Galaxies in catalog: {len(df):,}")
    lines.append(f"- Clean spirals (spiral flag = 1): {len(spir):,} ({spiral_fraction:.3f}% of the catalog)")
    lines.append("")
    lines.append("## Spiral arms — argmax of the debiased votes")
    lines.append("")
    lines.append("| arms | galaxies | % of arm-valid | arm rung ln(n)/ln(phi) | drift | Fibonacci family |")
    lines.append("|---|---|---|---|---|---|")
    for i, c in enumerate(arm_counts):
        n = i + 1
        r = rung(n)
        fib = (n in FIB) or i == 4
        lines.append(f"| {ARM_LABEL[i]} | {c:,} | {c / arm_valid * 100:.3f}% | {r:.4f} | {r - round(r):+.4f} | {'yes' if fib else 'no'} |")
    lines.append("")
    lines.append(f"Arm-valid galaxies: {arm_valid:,}. Fibonacci-family arm subjects (arms 1, 2, 3, 5+): {fib_subjects:,} "
                 f"({fib_subjects / arm_valid * 100:.3f}% of arm-valid).")
    lines.append("")
    lines.append("## Spiral winding — argmax of the debiased votes")
    lines.append("")
    lines.append("| winding | galaxies | % of winding-valid |")
    lines.append("|---|---|---|")
    for (k, _), c in zip(WIND.items(), wind_counts):
        lines.append(f"| {k} | {c:,} | {c / wind_valid * 100:.3f}% |")
    lines.append("")
    lines.append(f"Winding-valid galaxies: {wind_valid:,}.")
    lines.append("")
    lines.append("## Cross-check against the sealed ledger")
    lines.append("")
    lines.append("These counts reproduce gz2_trace_entries.json exactly: clean spirals 105,367; "
                 "arms 9,092 / 51,999 / 12,658 / 4,464 / 6,735; winding 57,552 / 35,489 / 11,892; "
                 "Fibonacci arm subjects 80,484. The report is the sealed trace, read whole from the source catalog.")
    lines.append("")
    lines.append("Generated by nasa_galaxy_zoo_phi.py on the local rail — no scraping, no guessing, measured votes in, rungs out.")
    out = os.path.join(HERE, "NASA_GALAXY_ZOO_PHI_REPORT.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"catalog={len(df)} clean_spirals={len(spir)} arm_valid={arm_valid} fib={fib_subjects}")
    print("wrote:", out)


if __name__ == "__main__":
    main()
